# ============================================================
#  run-soak.ps1 -- phase 157.1, the soak
#
#  Runs the emulator build for hours through Autorun cycles and fails on
#  what only time shows: a leak, a clock that steps backwards, a frame
#  lost with no reason given.
#
#    .\tests\run-soak.ps1                 # 4 hours
#    .\tests\run-soak.ps1 -Hours 0.5      # a short one, to check the soak
#    .\tests\run-soak.ps1 -Keep           # keep the recordings
#
#  Each cycle, alternating Kochab and Pherkad (neither sets here): a GoTo,
#  the target's profile, SEARCHING, PLANET LOCK, then RUNS: autofocus and
#  two 150-frame runs with a gap. The cycle script is generated into
#  tests\_build\soak.scn and run by the scenario runner (--scenario),
#  so it gets its own sandbox under test_runs\soak_<stamp>\.
#
#  It fails on:
#    - steady growth in the process's handles, private bytes or threads,
#      sampled every minute after a warm-up: the least-squares slope over
#      the LATER HALF of the samples above its limit AND the last quarter's
#      median above the first quarter's by half the limit times the hours
#      between them. A buffer allocated once and kept (the first recording
#      adds about 160 MB on the emulator) is a step, not a leak: it moves
#      the quarters but not the later half's slope;
#    - a recording whose trailer stamps do not each come after the one
#      before, or whose structure is wrong (tools\check_recordings.py
#      --scan, which shares no code with the writer);
#    - any "unexplained" frames in a run's drop ledger line;
#    - the cycle script failing before the deadline (a GoTo or a run not
#      finished; a lock refused is counted and its reason listed, not failed,
#      as is a lock made), with the scenario report's reason;
#    - no recording completed at all.
#
#  Too long for every push: nightly, or by hand on the imaging PC. The
#  report is reports\soak_<stamp>.txt, the samples beside it as
#  soak_<stamp>_samples.csv. Exit code 0 is a pass.
# ============================================================
param(
    [double]$Hours = 4,
    [int]$SampleSec = 60,
    [double]$WarmupMin = 10,
    [double]$HandlesPerHour = 100,
    [double]$PrivateMBPerHour = 64,
    [double]$ThreadsPerHour = 4,
    [switch]$Keep
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$exe  = Join-Path $root "build_emu\Release\RadukCapture.exe"
if (-not (Test-Path $exe)) { Write-Host "No emulator build at $exe - run build_all.bat"; exit 1 }
if (Get-Process RadukCapture -ErrorAction SilentlyContinue) {
    Write-Host "RadukCapture is open. Close it first: the soak will not run beside it."
    exit 1
}

$stamp   = Get-Date -Format "yyyyMMdd_HHmmss"
$reports = Join-Path $root "reports"
New-Item -ItemType Directory -Force -Path $reports | Out-Null
$repPath = Join-Path $reports "soak_$stamp.txt"
$csvPath = Join-Path $reports "soak_${stamp}_samples.csv"

# ── The cycle script ─────────────────────────────────────────
# One cycle takes a few minutes; this writes one per minute of the soak
# so it can never run out, and the deadline below ends it.
$cycles  = [int][math]::Ceiling($Hours * 60) + 2
$timeout = [int]($Hours * 3600) + 3600
$scn = @"
# Generated by tests\run-soak.ps1 ($stamp). Do not edit: it is rewritten.
name    Soak, $Hours h
timeout $timeout
rig     AutorunRuns=2
rig     AutorunGapSec=20
rig     AutorunRefocusEvery=1
rig     AutorunSeeingPct=0
rig     AutorunMinAltDeg=10
profile star.ini focuser position=168000
profile star.ini capture limit_value=150

expect 60 Started -- EMULATOR
wait   3
"@
# The lock is pressed every cycle but not required: a lock refused (the star
# left near the frame's edge by the GoTo's pointing error, with nothing to
# recentre it) would otherwise end a four-hour soak in its first hour. The
# report counts the locks made and lists every refusal's reason.
# Not Polaris: its tracking rates (about 0.05"/s az, 0.2"/s alt here) are under
# calibration's 0.5"/s "axes not moving" floor, so a LOCK there fails (found by
# the first trial soak, 2026-11-15; owed in Phase 157's plan).
$targets = @("Kochab", "Pherkad")
for ($i = 0; $i -lt $cycles; $i++) {
    $t = $targets[$i % 2]
    $scn += @"

# cycle $($i + 1): $t
goto   $t
expect 30  Auto-loading '$t' profile
expect 240 SEARCHING
wait   3
press  PLANET LOCK
wait   45
press  RUNS
expect 10  [AUTORUN] start: 2 runs
expect 900 [AUTORUN] end:
expect 10  [BUTTON] RUNS -> RUNS
wait   10
"@
}
$build = Join-Path $PSScriptRoot "_build"
New-Item -ItemType Directory -Force -Path $build | Out-Null
$scnPath = Join-Path $build "soak.scn"
# No byte-order mark: Windows PowerShell's utf8 writes one, and the
# scenario loader reads it as part of the first word.
[IO.File]::WriteAllText($scnPath, $scn, (New-Object Text.UTF8Encoding $false))

# ── Run and sample ───────────────────────────────────────────
$started  = Get-Date
$deadline = $started.AddHours($Hours)
Write-Host "Soak: $Hours h, until $($deadline.ToString('HH:mm')). Samples every $SampleSec s to $csvPath"
$p = Start-Process -FilePath $exe -ArgumentList @("--scenario", "`"$scnPath`"") -PassThru
"minute,handles,private_mb,working_mb,threads" | Set-Content -Path $csvPath -Encoding utf8
$samples = @()
$endedEarly = $false
while ((Get-Date) -lt $deadline) {
    if ($p.WaitForExit($SampleSec * 1000)) { $endedEarly = $true; break }
    try {
        $p.Refresh()
        $s = [pscustomobject]@{
            Minute   = [math]::Round(((Get-Date) - $started).TotalMinutes, 2)
            Handles  = $p.HandleCount
            Private  = [math]::Round($p.PrivateMemorySize64 / 1MB, 1)
            Working  = [math]::Round($p.WorkingSet64 / 1MB, 1)
            Threads  = $p.Threads.Count
        }
    } catch { continue }
    $samples += $s
    "$($s.Minute),$($s.Handles),$($s.Private),$($s.Working),$($s.Threads)" | Add-Content -Path $csvPath
}

$closedHow = "ended by itself"
if (-not $endedEarly) {
    # The deadline: ask the main window to close, so a run in progress is
    # stopped and its file closed, as a person quitting would. Found by
    # name: Process.CloseMainWindow picks whichever top-level window .NET
    # thinks is main, often a panel whose close only hides it, and the
    # first 30-minute soak (2026-11-15) was killed that way.
    # By enumeration, not FindWindow: PowerShell passes $null to a string
    # parameter as "", which makes FindWindow look for an empty title.
    Add-Type -Namespace RadukSoak -Name Win -MemberDefinition @'
public delegate bool EnumProc(IntPtr h, IntPtr l);
[DllImport("user32.dll")] static extern bool EnumWindows(EnumProc cb, IntPtr l);
[DllImport("user32.dll")] static extern uint GetWindowThreadProcessId(IntPtr h, out uint pid);
[DllImport("user32.dll", CharSet = CharSet.Unicode)]
static extern int GetClassNameW(IntPtr h, System.Text.StringBuilder sb, int n);
[DllImport("user32.dll")] static extern bool IsWindowVisible(IntPtr h);
[DllImport("user32.dll")] public static extern bool PostMessageW(IntPtr h, uint msg, IntPtr w, IntPtr l);
// The first top-level window of process `pid` with class `cls`, visible if asked.
public static IntPtr Find(uint pid, string cls, bool visibleOnly) {
    IntPtr found = IntPtr.Zero;
    EnumWindows((h, l) => {
        uint o; GetWindowThreadProcessId(h, out o);
        if (o != pid || (visibleOnly && !IsWindowVisible(h))) return true;
        var sb = new System.Text.StringBuilder(64);
        GetClassNameW(h, sb, 64);
        if (sb.ToString() == cls) { found = h; return false; }
        return true;
    }, IntPtr.Zero);
    return found;
}
'@
    $h = [RadukSoak.Win]::Find([uint32]$p.Id, "RadukCaptureWindow", $false)
    if ($h -ne [IntPtr]::Zero) {
        $null = [RadukSoak.Win]::PostMessageW($h, 0x0010, [IntPtr]::Zero, [IntPtr]::Zero)   # WM_CLOSE
        # A run recording at the deadline asks "Stop recording and exit?",
        # No by default. Answer Yes, as a person quitting would.
        for ($i = 0; $i -lt 10 -and -not $p.HasExited; $i++) {
            Start-Sleep -Milliseconds 500
            $dlg = [RadukSoak.Win]::Find([uint32]$p.Id, "#32770", $true)
            if ($dlg -ne [IntPtr]::Zero) {
                $null = [RadukSoak.Win]::PostMessageW($dlg, 0x0111, [IntPtr]6, [IntPtr]::Zero)   # WM_COMMAND IDYES
                break
            }
        }
    } else {
        $null = $p.CloseMainWindow()
    }
    if ($p.WaitForExit(90000)) { $closedHow = "closed at the deadline" }
    else { $p.Kill(); $p.WaitForExit(); $closedHow = "KILLED: did not close within 90 s of being asked" }
}
$elapsedH = ((Get-Date) - $started).TotalHours

# ── Judge ────────────────────────────────────────────────────
$problems = @()
$lines = @()

$box = Get-ChildItem (Join-Path $root "test_runs") -Directory -Filter "soak_*" -ErrorAction SilentlyContinue |
       Where-Object { $_.CreationTime -ge $started.AddSeconds(-2) } |
       Sort-Object CreationTime | Select-Object -Last 1
if (-not $box) { $problems += "no sandbox was made (exit code $($p.ExitCode))" }
if ($closedHow -like "KILLED*") { $problems += "the app $closedHow" }

if ($endedEarly -and $box) {
    $rep = Join-Path $box.FullName "report.txt"
    $why = "no report (exit code $($p.ExitCode))"
    if (Test-Path $rep) {
        $text = Get-Content $rep -Raw
        $res = if ($text -cmatch '(?m)^Result: (\w+)') { $Matches[1] } else { "?" }
        $why = if ($text -cmatch '(?m)^Why: (.+)') { $Matches[1].Trim() } else { "Result $res" }
        if ($res -eq "PASS") { $why = "" ; $lines += "The cycle script ran out before the deadline (it should not)." }
    }
    if ($why) { $problems += "the cycle script stopped after $([math]::Round($elapsedH * 60)) min: $why" }
}

# Growth, after the warm-up.
function Slope($xs, $ys) {
    $n = $xs.Count; $mx = ($xs | Measure-Object -Average).Average; $my = ($ys | Measure-Object -Average).Average
    $num = 0.0; $den = 0.0
    for ($i = 0; $i -lt $n; $i++) { $num += ($xs[$i] - $mx) * ($ys[$i] - $my); $den += ($xs[$i] - $mx) * ($xs[$i] - $mx) }
    if ($den -eq 0) { return 0.0 } else { return $num / $den }
}
function Median($v) { $s = @($v | Sort-Object); if (-not $s.Count) { return 0 }; return $s[[int][math]::Floor(($s.Count - 1) / 2)] }

$judged = @($samples | Where-Object { $_.Minute -ge $WarmupMin })
if ($judged.Count -lt 8) {
    $lines += "Growth: not judged, $($judged.Count) samples after the $WarmupMin-minute warm-up (8 needed)."
} else {
    $hrs = @($judged | ForEach-Object { $_.Minute / 60.0 })
    $q   = [int][math]::Max(2, [math]::Floor($judged.Count / 4))
    $spanH = ($judged[-1].Minute - $judged[0].Minute) / 60.0 * (1 - 1.0 / 4)   # first quarter's middle to last's
    foreach ($m in @(
        @{ Name = "handles";     Prop = "Handles"; Limit = $HandlesPerHour;   Unit = "" },
        @{ Name = "private MB";  Prop = "Private"; Limit = $PrivateMBPerHour; Unit = " MB" },
        @{ Name = "threads";     Prop = "Threads"; Limit = $ThreadsPerHour;   Unit = "" })) {
        $ys = @($judged | ForEach-Object { [double]$_.($m.Prop) })
        $h0    = [int][math]::Floor($ys.Count / 2)
        $slope = Slope ($hrs[$h0..($hrs.Count - 1)]) ($ys[$h0..($ys.Count - 1)])
        $first = Median ($ys[0..($q - 1)])
        $last  = Median ($ys[($ys.Count - $q)..($ys.Count - 1)])
        $rise  = $last - $first
        $lvl   = 0.5 * $m.Limit * [math]::Max($spanH, 0.01)
        $row = "Growth, $($m.Name): {0:+0.0;-0.0} per hour over the later half (limit $($m.Limit)); first quarter median $first, last $last ({1:+0.0;-0.0})." -f $slope, $rise
        $lines += $row
        if ($slope -gt $m.Limit -and $rise -gt $lvl) {
            $problems += "steady growth in $($m.Name): {0:0.0} per hour, last quarter up {1:0.0} on the first" -f $slope, $rise
        }
    }
}

# The recordings, read by the independent reader.
$recCount = 0
if ($box) {
    $caps = Join-Path $box.FullName "captures"
    $files = @(Get-ChildItem $caps -Recurse -File -ErrorAction SilentlyContinue |
               Where-Object { $_.Extension -in ".ser", ".fits", ".fit" })
    $recCount = $files.Count
    if ($recCount) {
        $py = if (Get-Command python -ErrorAction SilentlyContinue) { "python" } else { "py" }
        $json = Join-Path $reports "soak_${stamp}_files.json"
        $null = & $py (Join-Path $root "tools\check_recordings.py") --scan $caps --json $json
        if (Test-Path $json) {
            $r = Get-Content $json -Raw | ConvertFrom-Json
            $lines += "Recordings: $($r.passed) of $($r.passed + $r.failed) pass the independent reader ($json)."
            foreach ($f in @($r.files | Where-Object { -not $_.ok })) {
                $problems += "$($f.file): $($f.problems -join '; ')"
            }
        } else { $problems += "check_recordings.py wrote no verdicts" }
    } else { $problems += "no recording was completed" }

    # The drop ledger: every run logs a "Frames:" line ending in "N unexplained".
    $logs = @(Get-ChildItem $box.FullName -Recurse -File -Include "raduk_log*.txt" -ErrorAction SilentlyContinue)
    $runs = 0; $unexplained = 0
    foreach ($l in $logs) {
        foreach ($m in (Select-String -Path $l.FullName -Pattern 'Frames: .*?(\d+) unexplained' -AllMatches)) {
            $runs++
            $n = [int]$m.Matches[0].Groups[1].Value
            if ($n -gt 0) { $unexplained += $n; $problems += "unexplained drops: $($m.Line.Trim())" }
        }
    }
    $lines += "Drop ledger: $runs runs timed, $unexplained unexplained frames."

    # The locks: made, and refused with their reasons. Reported, not failed.
    $made = 0; $refused = @{}
    foreach ($l in $logs) {
        $made += @(Select-String -Path $l.FullName -SimpleMatch 'Auto-acquire complete - LOCKED').Count
        foreach ($m in (Select-String -Path $l.FullName -Pattern '\[ACQ\] Calibration FAILED: (.+?)( \S+ back to SEARCHING)?$')) {
            $why = $m.Matches[0].Groups[1].Value -replace '\(\d+, \d+ of \d+x\d+\)', '(x, y)'
            $refused[$why] = 1 + [int]$refused[$why]
        }
    }
    $nRefused = ($refused.Values | Measure-Object -Sum).Sum
    $lines += "Locks: $made made, $([int]$nRefused) refused."
    foreach ($k in $refused.Keys) { $lines += "  refused $($refused[$k])x: $k" }

    if (-not $Keep) {
        $files | Remove-Item -Force -ErrorAction SilentlyContinue
    }
}

# ── Report ───────────────────────────────────────────────────
$verdict = if ($problems.Count) { "FAIL" } else { "PASS" }
$out = @(
    "Soak $stamp",
    "Result: $verdict",
    ("Ran: {0:0.00} h of {1} h; the app {2}." -f $elapsedH, $Hours, $closedHow),
    "Sandbox: $(if ($box) { $box.FullName } else { '(none)' })",
    "Samples: $($samples.Count), in $csvPath",
    "Recordings: $recCount$(if (-not $Keep) { ' (deleted; -Keep keeps them)' })",
    ""
) + $lines
if ($problems.Count) { $out += ""; $out += "Problems:"; $out += ($problems | ForEach-Object { "  - $_" }) }
$out | Set-Content -Path $repPath -Encoding utf8
$out | ForEach-Object { Write-Host $_ }
Write-Host ""
Write-Host "Report: $repPath"
exit $(if ($verdict -eq "PASS") { 0 } else { 1 })
